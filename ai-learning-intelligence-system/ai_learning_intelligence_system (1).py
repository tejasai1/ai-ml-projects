import random

def generate_quiz(topic=None, num_questions=5):
    """
    Generate a quiz from the knowledge base.
    If topic is specified, generates questions for that topic only.
    If topic is None, generates questions across all topics.
    """
    print(f"\n{'='*60}")
    if topic:
        print(f"QUIZ — Topic: {topic}")
    else:
        print(f"QUIZ — Mixed topics")
    print('='*60)

    # Step 1 — select documents to quiz on
    if topic:
        topic_docs = [doc for doc in knowledge_base
                      if doc['topic'].lower() == topic.lower()]
        if not topic_docs:
            print(f"Topic '{topic}' not found in knowledge base.")
            print(f"Available topics: {list(set(d['topic'] for d in knowledge_base))}")
            return None
        selected_docs = random.sample(
            topic_docs, min(num_questions, len(topic_docs))
        )
    else:
        selected_docs = random.sample(
            knowledge_base, min(num_questions, len(knowledge_base))
        )

    # Step 2 — build quiz generation prompt
    docs_text = ""
    for i, doc in enumerate(selected_docs, 1):
        docs_text += f"\nDocument {i} [{doc['topic']}]: {doc['title']}\n{doc['content'][:300]}...\n"

    prompt = f"""You are an expert AI/ML tutor creating a quiz for a graduate student
preparing for AI internships.

Based on the following study materials, generate exactly {num_questions} multiple choice
questions. Each question must have 4 options (A, B, C, D) and one correct answer.

Study materials:
{docs_text}

Format each question EXACTLY like this:
Q1: [question text]
A) [option]
B) [option]
C) [option]
D) [option]
Answer: [correct letter]
Explanation: [one sentence explaining why]

Generate {num_questions} questions now:"""

    # Step 3 — call Groq
    response = groq_client.chat.completions.create(
        model="llama-3.1-8b-instant",
        messages=[{"role": "user", "content": prompt}],
        max_tokens=1500,
        temperature=0.7
    )

    quiz_text = response.choices[0].message.content

    # Step 4 — parse quiz into structured format
    questions = []
    lines = quiz_text.strip().split('\n')
    current_q = {}

    for line in lines:
        line = line.strip()
        if not line:
            continue
        if line.startswith('Q') and ':' in line and len(line) < 200:
            if current_q and 'question' in current_q:
                questions.append(current_q)
            current_q = {'question': line.split(':', 1)[1].strip(),
                         'options': {}, 'answer': '', 'explanation': ''}
        elif line.startswith(('A)', 'B)', 'C)', 'D)')):
            letter = line[0]
            current_q['options'][letter] = line[3:].strip()
        elif line.startswith('Answer:'):
            current_q['answer'] = line.replace('Answer:', '').strip()
        elif line.startswith('Explanation:'):
            current_q['explanation'] = line.replace('Explanation:', '').strip()

    if current_q and 'question' in current_q:
        questions.append(current_q)

    # Step 5 — display quiz interactively
    print(f"\nGenerated {len(questions)} questions. Let's begin!\n")

    score = 0
    results = []

    for i, q in enumerate(questions, 1):
        print(f"Q{i}: {q['question']}")
        for letter, option in q['options'].items():
            print(f"   {letter}) {option}")

        # Get user answer
        while True:
            user_answer = input("\nYour answer (A/B/C/D) or 'skip': ").strip().upper()
            if user_answer in ['A', 'B', 'C', 'D', 'SKIP']:
                break
            print("Please enter A, B, C, D, or 'skip'")

        if user_answer == 'SKIP':
            print(f"Skipped. Correct answer: {q['answer']}")
            print(f"Explanation: {q['explanation']}\n")
            results.append({'question': q['question'], 'status': 'skipped',
                           'correct_answer': q['answer']})
        elif user_answer == q['answer']:
            score += 1
            print(f"✅ Correct! {q['explanation']}\n")
            results.append({'question': q['question'], 'status': 'correct',
                           'user_answer': user_answer, 'correct_answer': q['answer']})
        else:
            print(f"❌ Incorrect. Correct answer: {q['answer']}")
            print(f"Explanation: {q['explanation']}\n")
            results.append({'question': q['question'], 'status': 'incorrect',
                           'user_answer': user_answer, 'correct_answer': q['answer']})

    # Step 6 — show score
    answered = len([r for r in results if r['status'] != 'skipped'])
    print(f"\n{'='*60}")
    print(f"QUIZ COMPLETE — Score: {score}/{answered} ({score/max(answered,1)*100:.0f}%)")
    print('='*60)

    if answered > 0:
        pct = score / answered * 100
        if pct >= 80:
            print("🌟 Excellent! You have strong understanding of this material.")
        elif pct >= 60:
            print("👍 Good work! Review the questions you missed.")
        else:
            print("📚 Keep studying! Focus on the topics you missed.")

    # Step 7 — identify weak topics
    weak_topics = []
    for r in results:
        if r['status'] == 'incorrect':
            weak_topics.append(r['question'][:50])

    if weak_topics:
        print(f"\n⚠️  Topics to review:")
        for t in weak_topics:
            print(f"   → {t}...")

    return {
        'score':       score,
        'total':       answered,
        'percentage':  score / max(answered, 1) * 100,
        'results':     results,
        'weak_topics': weak_topics
    }


