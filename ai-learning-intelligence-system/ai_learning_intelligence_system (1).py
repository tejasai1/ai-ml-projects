def retrieve(query, n_results=3, min_confidence=0.3):
    """
    Retrieve most relevant documents for a query.

    Args:
        query: natural language question
        n_results: number of documents to retrieve (top-k)
        min_confidence: minimum confidence threshold (0-1)

    Returns:
        dict with retrieved docs, scores, and confidence assessment
    """

    # Step 1 — embed the query
    query_embedding = embedding_model.encode([query]).tolist()

    # Step 2 — search ChromaDB
    results = collection.query(
        query_embeddings=query_embedding,
        n_results=n_results,
        include=['documents', 'metadatas', 'distances']
    )

    # Step 3 — convert distances to confidence scores
    # ChromaDB returns L2 distances — lower = more similar
    # Convert to 0-1 confidence: confidence = 1 / (1 + distance)
    retrieved = []
    for i in range(len(results['documents'][0])):
        distance = results['distances'][0][i]
        confidence = round(1 / (1 + distance), 3)

        retrieved.append({
            'content':    results['documents'][0][i],
            'title':      results['metadatas'][0][i]['title'],
            'topic':      results['metadatas'][0][i]['topic'],
            'id':         results['metadatas'][0][i]['id'],
            'confidence': confidence,
            'distance':   round(distance, 4)
        })

    # Step 4 — assess overall retrieval confidence
    if retrieved:
        top_confidence = retrieved[0]['confidence']
        if top_confidence >= 0.6:
            assessment = "HIGH"
        elif top_confidence >= min_confidence:
            assessment = "MEDIUM"
        else:
            assessment = "LOW — possible knowledge gap"
    else:
        assessment = "NO RESULTS"
        top_confidence = 0.0

    return {
        'query':          query,
        'results':        retrieved,
        'top_confidence': top_confidence,
        'assessment':     assessment,
        'gap_detected':   top_confidence < min_confidence
    }


